// The competitive formats the app offers (gens 4 to 9) and, for each, the species a team may use.
// Legality comes from Showdown's own validator (@pkmn/sim, a devDependency: never shipped to the browser),
// so tier bans, clauses, regional dexes and level rules are the real ones.
// Regenerate: node apps/web/scripts/build-formats.mjs (after a @pkmn/sim update)
// Out: src/data/formats/index.ts (the catalogue) + src/data/formats/<id>.json (legal species, dex order)
import assert from "node:assert/strict";
import { mkdirSync, writeFileSync } from "node:fs";
import { Dex as DataDex } from "@pkmn/dex";
import { Dex, TeamValidator } from "@pkmn/sim";

const OUT = new URL("../src/data/formats/", import.meta.url);

// Smogon singles tiers per generation, as Showdown still runs them (no RU in gen 4).
const SMOGON_TIERS = ["ubers", "ou", "uu", "ru", "nu", "pu", "zu", "lc"];
const SMOGON = Object.fromEntries(
  [9, 8, 7, 6, 5, 4].map((gen) => [gen, SMOGON_TIERS.filter((t) => !(gen === 4 && t === "ru"))]),
);
// Past VGC seasons Showdown still ships (none for gen 4).
const VGC = {
  8: ["vgc2022", "vgc2021"],
  7: ["vgc2019", "vgc2018"],
  6: ["vgc2016", "vgc2015"],
  5: ["vgc2013"],
};
// Gen 9 regulations: Showdown dropped F and H, so all four keep the app's per-species tag bans.
// shortcut: per-species bans only; G (1) and I (2) also cap restricted legendaries per team, not enforced yet.
const GEN9_VGC = {
  gen9vgc2026regf: { rules: "F", banned: ["Restricted Legendary", "Mythical"] },
  gen9vgc2025regg: { rules: "G", banned: ["Mythical"] },
  gen9vgc2025regh: {
    rules: "H",
    banned: ["Restricted Legendary", "Mythical", "Sub-Legendary", "Paradox"],
  },
  gen9vgc2026regi: { rules: "I", banned: ["Mythical"] },
};

// Species a player picks: no battle-only formes (Megas, Primals), cosmetic ones, Gigantamax or Totems.
const pickable = (s) =>
  s.exists && !s.battleOnly && !s.isCosmeticForme && !/-(Gmax|Totem|Eternamax)$/.test(s.name);
const byDex = (a, b) => a.num - b.num || a.name.localeCompare(b.name);

// Legal if one of its abilities passes the validator. Only species-level problems count: the probe set
// has a placeholder move, so move complaints are ignored. 1 EV avoids the "did you forget to EV it?" check.
function legalSpecies(id) {
  const format = Dex.formats.get(id);
  assert.ok(format.exists, `unknown format ${id}`);
  const dex = Dex.forFormat(format);
  const validator = TeamValidator.get(format);
  const ruleTable = Dex.formats.getRuleTable(format);
  const level = ruleTable.adjustLevel || ruleTable.maxLevel || 100;
  const zeros = { hp: 0, atk: 0, def: 0, spa: 0, spd: 0, spe: 0 };
  // Perfect IVs: legendaries must have at least three.
  const perfect = { hp: 31, atk: 31, def: 31, spa: 31, spd: 31, spe: 31 };
  return dex.species
    .all()
    .filter(pickable)
    .filter((s) =>
      Object.values(s.abilities).some((ability) => {
        const problems = validator.validateSet(
          {
            name: s.name,
            species: s.name,
            item: "",
            ability,
            moves: ["Protect"],
            nature: "Serious",
            gender: "",
            evs: { ...zeros, hp: 1 },
            ivs: perfect,
            level,
          },
          {},
        );
        return !(problems ?? []).some((p) => !/learn|move/i.test(p));
      }),
    )
    .sort(byDex)
    .map((s) => s.name);
}

const catalogue = [];
const write = (entry, species) => {
  assert.ok(species.length > 100, `${entry.id}: only ${species.length} legal species`);
  writeFileSync(new URL(`${entry.id}.json`, OUT), JSON.stringify(species));
  catalogue.push(entry);
  console.log(`${entry.id.padEnd(18)} ${String(species.length).padStart(4)} species`);
};
// "[Gen 6] VGC 2016" -> "VGC 2016"
const shortName = (id) => Dex.formats.get(id).name.replace(/^\[Gen \d\] /, "");

mkdirSync(OUT, { recursive: true });
for (const gen of [9, 8, 7, 6, 5, 4]) {
  for (const tier of SMOGON[gen]) {
    const id = `gen${gen}${tier}`;
    write({ id, gen, mode: "smogon", name: shortName(id) }, legalSpecies(id));
  }
  if (gen === 9) {
    const dex = DataDex.forGen(9);
    for (const [id, { rules, banned }] of Object.entries(GEN9_VGC)) {
      const species = dex.species
        .all()
        .filter((s) => pickable(s) && !s.isNonstandard && !s.tags.some((t) => banned.includes(t)))
        .sort(byDex)
        .map((s) => s.name);
      write({ id, gen, mode: "vgc", name: `Regulation ${rules}`, rules }, species);
    }
  }
  for (const season of VGC[gen] ?? []) {
    const id = `gen${gen}${season}`;
    write({ id, gen, mode: "vgc", name: shortName(id) }, legalSpecies(id));
  }
}

writeFileSync(
  new URL("index.ts", OUT),
  `// Generated by scripts/build-formats.mjs. Do not edit.
// Each format's legal species are in ./<id>.json, loaded on demand.
export const FORMATS = ${JSON.stringify(catalogue, null, 2)} as const;
`,
);
console.log(`${catalogue.length} formats`);

// Maps alternate formes (@pkmn/dex names) to PokeAPI pokemon ids, whose official artwork is stored by id.
// Base species need no entry: their PokeAPI id is their national dex number.
// Regenerate: node apps/web/scripts/build-form-artwork-ids.mjs
import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { Dex } from "@pkmn/dex";
import { POKEAPI_REV, loadCsv } from "./lib/pokeapi.mjs";

const OUT = new URL("../src/data/form-artwork-ids.ts", import.meta.url);
const GENS = [4, 5, 6, 7, 8, 9]; // adventure (gen 4) and the competitive generations

const ids = new Map((await loadCsv("pokemon")).map((p) => [p.identifier, Number(p.id)]));

const slug = (name) =>
  name.toLowerCase().normalize("NFD").replace(/\p{M}/gu, "").replace(/[.'’:%]/g, "").replace(/ /g, "-");

// PokeAPI names formes a bit differently: "tauros-paldea-aqua-breed", "ogerpon-wellspring-mask", "necrozma-dusk".
function resolve(name) {
  const s = slug(name);
  if (ids.has(s)) return ids.get(s);
  // Shortest prefix match: "meowstic-f" → "meowstic-female", not "meowstic-female-mega".
  const [prefixed] = [...ids.keys()].filter((k) => k.startsWith(s)).sort((a, b) => a.length - b.length);
  if (prefixed) return ids.get(prefixed);
  const shorter = s.split("-").slice(0, -1).join("-");
  const id = ids.get(shorter);
  return id && id > 10000 ? id : undefined; // a base id would just repeat the fallback
}

const map = {};
for (const gen of GENS) {
  for (const s of Dex.forGen(gen).species.all()) {
    if (!s.exists || s.isNonstandard || !s.forme) continue;
    const id = resolve(s.name);
    if (id) map[s.name] = id;
  }
}

assert.equal(map["Urshifu-Rapid-Strike"], 10191);
assert.ok(map["Sandshrew-Alola"]);
assert.ok(map["Tauros-Paldea-Aqua"]);
assert.ok(map["Ogerpon-Wellspring"]);

const sorted = Object.fromEntries(Object.entries(map).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(
  OUT,
  `// Generated by scripts/build-form-artwork-ids.mjs from PokeAPI ${POKEAPI_REV.slice(0, 7)}. Do not edit.\n` +
    `export const FORM_ARTWORK_IDS: Record<string, number> = ${JSON.stringify(sorted, null, 2)};\n`,
);
console.log(`${Object.keys(sorted).length} formes mapped`);
